-- Les remarques du Greffier vivent à côté du débat : elles n'appartiennent à aucun tour,
-- et les sages ne les lisent pas. after_turns : le nombre d'interventions déjà prononcées.
CREATE TABLE scribe_note (
    note_id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_content     TEXT         NOT NULL,
    note_after_turns INT          NOT NULL,
    note_model       VARCHAR(100) NULL,
    note_created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    session_id       INT          NOT NULL,
    CONSTRAINT uq_scribe_note UNIQUE (session_id, note_after_turns),
    CONSTRAINT fk_scribe_note_session FOREIGN KEY (session_id)
        REFERENCES "session" (session_id) ON DELETE CASCADE
);

-- Reprend les notes rangées jusqu'ici dans les tours
INSERT INTO scribe_note (note_content, note_after_turns, note_model, note_created_at, session_id)
SELECT DISTINCT ON (notes.session_id, notes.after_turns)
       notes.message_content, notes.after_turns, notes.message_model, notes.message_created_at, notes.session_id
FROM (SELECT m.message_content, m.message_model, m.message_created_at, st.session_id,
             (SELECT count(*)
              FROM message earlier
                       JOIN step earlier_step ON earlier_step.step_id = earlier.step_id
                       JOIN sage earlier_sage ON earlier_sage.participant_id = earlier.participant_id
              WHERE earlier_step.session_id = st.session_id
                AND earlier_sage.sage_kind = 'DEBATER'
                AND earlier.message_id < m.message_id) AS after_turns
      FROM message m
               JOIN step st ON st.step_id = m.step_id
               JOIN sage s ON s.participant_id = m.participant_id
      WHERE s.sage_kind = 'SCRIBE' AND st.step_order < 4) AS notes
ORDER BY notes.session_id, notes.after_turns, notes.message_created_at;

DELETE FROM message m
USING step st, sage s
WHERE st.step_id = m.step_id AND s.participant_id = m.participant_id
  AND s.sage_kind = 'SCRIBE' AND st.step_order < 4;
